    "PATIENT_CONTACT_VIEW", "CATALOG_MANAGE", "ESTIMATE_MANAGE", "ESTIMATE_RECORD_OFFLINE_APPROVAL",
    "INVOICE_DRAFT", "PAYMENT_RECORD", "SETTINGS_MANAGE",
