export const ROLES = ["OWNER", "CLINIC_ADMIN", "RECEPTIONIST", "PHYSIOTHERAPIST", "BILLING", "ACCOUNTANT", "CONTENT_EDITOR"] as const;
export type Role = (typeof ROLES)[number];

